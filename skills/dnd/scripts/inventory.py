#!/usr/bin/env python3
"""Own every character's items and coins, and the party's shared cargo.

The ledger is the truth; the sheet's `## Equipment & Inventory` section is
generated from it. The DM never counts coins or rewrites that section by hand:
every gain, loss, purchase, sale and equip goes through this script, which does
the coin maths (making change across denominations), refuses what cannot
happen, rewrites the sheet section and pushes the result to the display.

Files, per campaign:
    characters/<sheet>.inventory.json   one character's items and coins
    party_inventory.json                shared cargo (the wagon and its load)

    inventory.py show    --campaign C [--character X]
    inventory.py add     --campaign C --character X "Rope" [--qty 2] [--category gear]
    inventory.py remove  --campaign C --character X "Torch" [--qty 1 | --all]
    inventory.py earn    --campaign C --character X "5 gp 3 sp"
    inventory.py spend   --campaign C --character X "2 gp 5 sp"
    inventory.py buy     --campaign C --character X "Lantern" --price "5 gp" [--qty 1]
    inventory.py sell    --campaign C --character X "Blanket" --price "24 sp" [--qty 4]
    inventory.py equip   --campaign C --character X "Shield"      (unequip to take off)
    inventory.py cargo   --campaign C add|remove|show ["Flour sack"] [--qty N]
    inventory.py migrate --campaign C --character X [--write]
    inventory.py sync    --campaign C          regenerate every sheet section and push
"""

