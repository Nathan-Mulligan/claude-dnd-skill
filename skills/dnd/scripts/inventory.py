CHANGE_DENOMS = ("gp", "sp", "cp")  # merchants give change in common coin
CATEGORIES = ("weapons", "armour", "gear", "tools", "consumables", "trade goods", "treasure")
LABELS = {
    "weapons": "Weapons", "armour": "Armour", "gear": "Adventuring Gear",
    "tools": "Tools", "consumables": "Consumables", "trade goods": "Trade Goods",
    "treasure": "Treasure",
}
